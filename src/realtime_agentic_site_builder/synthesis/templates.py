API_CLIENT: Final = """\
import { useCallback, useState } from "react";

@@MODELS_IMPORT@@export interface ProblemDetails {
  type?: string;
  title?: string;
  status?: number;
  detail?: string;
  instance?: string;
  [extension: string]: unknown;
}

export class ApiError extends Error {
  readonly status: number;
  readonly problem: ProblemDetails;

  constructor(status: number, problem: ProblemDetails) {
    super(problem.detail ?? problem.title ?? `Request failed with status ${status}`);
    this.name = "ApiError";
    this.status = status;
    this.problem = problem;
  }
}

export interface RequestOptions {
  query?: Record<string, string | number | boolean>;
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

const BASE_URL: string = import.meta.env.VITE_API_BASE_URL ?? "";

async function request<T>(
  method: string,
  path: string,
  options: RequestOptions = {},
  body?: unknown,
): Promise<T> {
  const entries = Object.entries(options.query ?? {}).map(
    ([key, value]): [string, string] => [key, String(value)],
  );
  const query = entries.length > 0 ? `?${new URLSearchParams(entries)}` : "";
  const response = await fetch(`${BASE_URL}${path}${query}`, {
    method,
    signal: options.signal,
    headers: {
      ...(body === undefined ? {} : { "Content-Type": "application/json" }),
      ...options.headers,
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  const isJson = (response.headers.get("Content-Type") ?? "").includes("json");
  const payload: unknown = text !== "" && isJson ? JSON.parse(text) : undefined;
  if (!response.ok) {
    throw new ApiError(response.status, (payload ?? {}) as ProblemDetails);
  }
  return payload as T;
}

export interface ApiCallState<R> {
  data: R | undefined;
  error: Error | undefined;
  loading: boolean;
}

export function useApiCall<A extends unknown[], R>(call: (...args: A) => Promise<R>) {
  const [state, setState] = useState<ApiCallState<R>>({
    data: undefined,
    error: undefined,
    loading: false,
  });
  const run = useCallback(
    async (...args: A): Promise<R> => {
      setState((previous) => ({ ...previous, error: undefined, loading: true }));
      try {
        const data = await call(...args);
        setState({ data, error: undefined, loading: false });
        return data;
      } catch (error) {
        const failure = error instanceof Error ? error : new Error(String(error));
        setState({ data: undefined, error: failure, loading: false });
        throw failure;
      }
    },
    [call],
  );
  return { ...state, run };
}
"""
