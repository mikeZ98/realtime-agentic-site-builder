ERRORS: Final = '''\
"""Renders every error as an RFC 9457 problem document."""

from http.client import responses

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse, Response
from starlette.exceptions import HTTPException

PROBLEM_JSON = "application/problem+json"


def _problem(
    request: Request,
    status: int,
    detail: str,
    *,
    headers: dict[str, str] | None = None,
    errors: list[dict[str, object]] | None = None,
) -> Response:
    body: dict[str, object] = {
        "type": "about:blank",
        "title": responses.get(status, "Error"),
        "status": status,
        "detail": detail,
        "instance": request.url.path,
    }
    if errors is not None:
        body["errors"] = errors
    return JSONResponse(body, status_code=status, media_type=PROBLEM_JSON, headers=headers)


def install_error_handlers(app: FastAPI) -> None:
    @app.exception_handler(HTTPException)
    async def _http_error(request: Request, error: HTTPException) -> Response:
        return _problem(
            request, error.status_code, str(error.detail), headers=dict(error.headers or {})
        )

    @app.exception_handler(RequestValidationError)
    async def _invalid_request(request: Request, error: RequestValidationError) -> Response:
        # The fields are picked one by one, so no part of the rejected input is echoed back.
        errors: list[dict[str, object]] = [
            {"loc": [str(part) for part in item["loc"]], "msg": item["msg"], "type": item["type"]}
            for item in error.errors()
        ]
        return _problem(request, 422, "The request failed validation.", errors=errors)

    @app.exception_handler(Exception)
    async def _unexpected(request: Request, _error: Exception) -> Response:
        return _problem(request, 500, "The server failed to handle this request.")
'''

